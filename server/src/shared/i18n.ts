let LANG: Lang = "en";

export function setLang(lang: Lang): void { LANG = lang; }
export function getLang(): Lang { return LANG; }
export function detectLang(): Lang {
  const nav: any = typeof globalThis !== "undefined" ? (globalThis as any).navigator : undefined;
  return (nav && (nav.language || "").toLowerCase().startsWith("zh")) ? "zh" : "en";
}
export function t(k: string): string {
  return (DICT[LANG][k] !== undefined) ? DICT[LANG][k] : k;
}

LANG = detectLang();
